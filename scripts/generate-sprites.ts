/**
 * Export Mocchi sprite sheets and app icons from the shared sprite model.
 *
 *   npm run sprites
 *
 * Output (see docs/character.md for the naming convention):
 *   assets/character/mocchi_<mood>.png                 base sheet, frames left→right
 *   assets/character/cosmetics/mocchi_<mood>_<id>.png  sheet with a cosmetic applied
 *   assets/character/manifest.json                     frame size, counts and timing
 *   assets/ui/icon-*.png, tray-*.png                   application and tray icons
 *   apps/mobile/src/sprites.generated.ts               static require() map for Metro
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ANIMATIONS, MOODS, SPRITE_SIZE, frameToRgba, renderFrame } from '../packages/design-system/src/sprites';
import { COSMETICS } from '../packages/learning-engine/src/progression';
import { encodePng } from './png';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const charDir = join(root, 'assets/character');
const cosDir = join(charDir, 'cosmetics');
const uiDir = join(root, 'assets/ui');
for (const d of [charDir, cosDir, uiDir]) mkdirSync(d, { recursive: true });

/** Sheets are exported at 8× so they stay crisp when platforms scale them down. */
const SCALE = 8;

function sheet(mood: (typeof MOODS)[number], cosmetic: string | null, scale = SCALE): Buffer {
  const frames = ANIMATIONS[mood].frames.length;
  const size = SPRITE_SIZE * scale;
  const out = new Uint8ClampedArray(size * frames * size * 4);
  for (let i = 0; i < frames; i++) {
    const px = frameToRgba(renderFrame(mood, i, cosmetic), scale);
    for (let y = 0; y < size; y++) {
      out.set(px.subarray(y * size * 4, (y + 1) * size * 4), (y * size * frames + i * size) * 4);
    }
  }
  return encodePng(size * frames, size, out);
}

const manifest: Record<string, unknown> = { frameSize: SPRITE_SIZE, scale: SCALE, moods: {} };
for (const mood of MOODS) {
  writeFileSync(join(charDir, `mocchi_${mood}.png`), sheet(mood, null));
  for (const c of COSMETICS) writeFileSync(join(cosDir, `mocchi_${mood}_${c.id}.png`), sheet(mood, c.id));
  (manifest.moods as Record<string, unknown>)[mood] = {
    frames: ANIMATIONS[mood].frames.length,
    frameMs: ANIMATIONS[mood].frameMs,
    loop: ANIMATIONS[mood].loop,
  };
}
writeFileSync(join(charDir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);

// Icons: the idle frame centred on a navy tile, and transparent tray icons.
function icon(size: number, background: boolean): Buffer {
  // Integer upscale where possible; nearest-neighbour downsample for tiny tray icons.
  const s = size >= SPRITE_SIZE ? SPRITE_SIZE * Math.max(1, Math.floor((background ? size * 0.8 : size) / SPRITE_SIZE)) : size;
  const sprite = frameToRgba(renderFrame('idle', 0, null), 1);
  const out = new Uint8ClampedArray(size * size * 4);
  if (background) for (let i = 0; i < size * size; i++) out.set([0x16, 0x1e, 0x37, 255], i * 4);
  const off = Math.floor((size - s) / 2);
  for (let y = 0; y < s; y++) {
    for (let x = 0; x < s; x++) {
      const si = (Math.floor((y * SPRITE_SIZE) / s) * SPRITE_SIZE + Math.floor((x * SPRITE_SIZE) / s)) * 4;
      if ((sprite[si + 3] ?? 0) === 0) continue;
      out.set(sprite.subarray(si, si + 4), ((y + off) * size + x + off) * 4);
    }
  }
  return encodePng(size, size, out);
}
for (const size of [256, 512, 1024]) writeFileSync(join(uiDir, `icon-${size}.png`), icon(size, true));
writeFileSync(join(uiDir, 'tray-16.png'), icon(16, false));
writeFileSync(join(uiDir, 'tray-32.png'), icon(32, false));
writeFileSync(join(uiDir, 'tray-64.png'), icon(64, false));
writeFileSync(join(uiDir, 'icon-adaptive-fg.png'), icon(1024, false));

// Metro needs static require() calls, so emit a map for the mobile app.
const lines = ['// Generated by scripts/generate-sprites.ts — do not edit.', '/* eslint-disable */', 'export const SPRITE_SHEETS: Record<string, Record<string, number>> = {'];
for (const mood of MOODS) {
  lines.push(`  ${JSON.stringify(mood)}: {`);
  lines.push(`    base: require('../../../assets/character/mocchi_${mood}.png'),`);
  for (const c of COSMETICS) lines.push(`    ${JSON.stringify(c.id)}: require('../../../assets/character/cosmetics/mocchi_${mood}_${c.id}.png'),`);
  lines.push('  },');
}
lines.push('};', '');
mkdirSync(join(root, 'apps/mobile/src'), { recursive: true });
writeFileSync(join(root, 'apps/mobile/src/sprites.generated.ts'), lines.join('\n'));

// Contact sheet for reviewing the whole set at a glance.
{
  const scale = 4;
  const cell = SPRITE_SIZE * scale;
  const cols = 4;
  const rows = MOODS.length;
  const w = cell * cols;
  const h = cell * rows;
  const out = new Uint8ClampedArray(w * h * 4);
  for (let i = 0; i < w * h; i++) out.set([0x16, 0x1e, 0x37, 255], i * 4);
  MOODS.forEach((mood, r) => {
    for (let c = 0; c < Math.min(cols, ANIMATIONS[mood].frames.length); c++) {
      const px = frameToRgba(renderFrame(mood, c, null), scale);
      for (let y = 0; y < cell; y++) for (let x = 0; x < cell; x++) {
        const si = (y * cell + x) * 4;
        if ((px[si + 3] ?? 0) === 0) continue;
        out.set(px.subarray(si, si + 4), ((r * cell + y) * w + c * cell + x) * 4);
      }
    }
  });
  writeFileSync(join(charDir, 'contact-sheet.png'), encodePng(w, h, out));
}

console.log(`Wrote ${MOODS.length} sheets, ${MOODS.length * COSMETICS.length} cosmetic sheets and icons.`);

// Cosmetics preview: idle frame 0 with each cosmetic.
{
  const scale = 4;
  const cell = SPRITE_SIZE * scale;
  const ids: Array<string | null> = [null, ...COSMETICS.map((c) => c.id)];
  const w = cell * ids.length;
  const out = new Uint8ClampedArray(w * cell * 4);
  for (let i = 0; i < w * cell; i++) out.set([0x16, 0x1e, 0x37, 255], i * 4);
  ids.forEach((id, n) => {
    const px = frameToRgba(renderFrame('idle', 0, id), scale);
    for (let y = 0; y < cell; y++) for (let x = 0; x < cell; x++) {
      const si = (y * cell + x) * 4;
      if ((px[si + 3] ?? 0) === 0) continue;
      out.set(px.subarray(si, si + 4), (y * w + n * cell + x) * 4);
    }
  });
  writeFileSync(join(charDir, 'cosmetics-sheet.png'), encodePng(w, cell, out));
}
