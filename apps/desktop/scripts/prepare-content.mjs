// Packaging step: check the built level packs (npm run content:build) and write
// installer/levels.generated.nsh with their file names, sizes and download URL.
// MOCCHI_CONTENT_URL overrides the manifest's base URL (e.g. a local test server).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dist = fileURLToPath(new URL('../../../dist/content/', import.meta.url));
const manifestPath = `${dist}manifest.json`;
if (!existsSync(manifestPath)) {
  console.error('dist/content/manifest.json is missing. Run `npm run content:fetch && npm run content:build` first.');
  process.exit(1);
}
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
let base = process.env.MOCCHI_CONTENT_URL ?? manifest.baseUrl;
if (!base.endsWith('/')) base += '/';
if (process.env.MOCCHI_CONTENT_URL) {
  // The installer and the app must agree on where packs come from.
  manifest.baseUrl = base;
  writeFileSync(manifestPath, JSON.stringify(manifest, null, 2));
}

const order = ['N5', 'N4', 'N3', 'N2', 'N1'];
const size = (bytes) => (bytes < 1024 * 1024 ? `${Math.max(1, Math.round(bytes / 1024))} KB` : `${(bytes / 1024 / 1024).toFixed(1)} MB`);
const lines = [`; Generated by scripts/prepare-content.mjs - do not edit.`, `!define MOCCHI_CONTENT_URL "${base}"`];
let total = 0;
for (const level of order) {
  const pack = manifest.packs.find((p) => p.level === level);
  if (!pack || !existsSync(`${dist}${pack.file}`)) {
    console.error(`Pack ${level} is missing from dist/content.`);
    process.exit(1);
  }
  if (level !== 'N5') total += pack.bytes;
  lines.push(`!define MOCCHI_${level}_FILE "${pack.file}"`, `!define MOCCHI_${level}_TOTAL "${size(total)}"`);
}
writeFileSync(fileURLToPath(new URL('../installer/levels.generated.nsh', import.meta.url)), `${lines.join('\r\n')}\r\n`);
console.log(`installer content: ${base} (N1 total download ${size(total)})`);
